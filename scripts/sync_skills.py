"""Mirror the repository skills for Claude Code.

The skills live in .agents/skills/<name>/ (where Codex and other agents look).
Claude Code discovers skills in .claude/skills/<name>/SKILL.md, so this script
writes a small pointer there with the same name and description. Edit only the
files in .agents/skills/, then run:

    uv run --locked python scripts/sync_skills.py          # write the mirrors
    uv run --locked python scripts/sync_skills.py --check  # fail if out of date
"""

import argparse
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / ".agents" / "skills"
MIRROR = ROOT / ".claude" / "skills"
FRONTMATTER = re.compile(r"\A---\n(.*?)\n---\n", re.DOTALL)


def pointer(name: str, frontmatter: str) -> str:
    return (
        f"---\n{frontmatter}\n---\n\n"
        f"<!-- Generated by scripts/sync_skills.py from .agents/skills/{name}/. Do not edit. -->\n\n"
        f"# {name}\n\n"
        f"Read and follow `.agents/skills/{name}/SKILL.md` (relative to the repository root)\n"
        f"before doing anything else. Its `references/`, `assets/` and `scripts/` folders are\n"
        f"in the same directory; open only the ones that skill tells you to use.\n"
    )


def expected() -> dict[Path, str]:
    files = {}
    for skill in sorted(path for path in SOURCE.iterdir() if (path / "SKILL.md").is_file()):
        text = (skill / "SKILL.md").read_text(encoding="utf-8").replace("\r\n", "\n")
        match = FRONTMATTER.match(text)
        if not match:
            raise SystemExit(f"{skill / 'SKILL.md'}: missing front matter")
        files[MIRROR / skill.name / "SKILL.md"] = pointer(skill.name, match.group(1))
    return files


def stale() -> list[str]:
    wanted = expected()
    problems = [str(path.relative_to(ROOT)) for path, text in wanted.items()
                if not path.is_file() or path.read_text(encoding="utf-8").replace("\r\n", "\n") != text]
    if MIRROR.is_dir():
        known = {path.parent for path in wanted}
        problems += [str(path.relative_to(ROOT)) for path in MIRROR.iterdir() if path.is_dir() and path not in known]
    return problems


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="Only report mirrors that are out of date.")
    args = parser.parse_args()
    if args.check:
        problems = stale()
        for problem in problems:
            print("out of date:", problem)
        sys.exit(1 if problems else 0)
    wanted = expected()
    if MIRROR.is_dir():
        for path in MIRROR.iterdir():
            if path.is_dir() and path not in {target.parent for target in wanted}:
                shutil.rmtree(path)
    for path, text in wanted.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        print("wrote", path.relative_to(ROOT))


if __name__ == "__main__":
    main()
